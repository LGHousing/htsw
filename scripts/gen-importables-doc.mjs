import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import {
    IMPORT_JSON_SCHEMA,
    IMPORT_JSON_SCHEMA_DEFINITIONS,
} from "../language/src/importjson/schemaSpec.ts";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = path.join(repositoryRoot, "docs", "importables.md");
const checkOnly = process.argv.includes("--check");
const markerPattern =
    /<!-- importables-schema:([A-Za-z0-9-]+) START -->[\s\S]*?<!-- importables-schema:\1 END -->/g;

const importableDefinitionNames = Object.values(IMPORT_JSON_SCHEMA.properties)
    .filter(
        (property) =>
            property.kind === "array" &&
            property.items.kind === "ref" &&
            property.items.ref.endsWith("Importable")
    )
    .map((property) => property.items.ref);
const expectedMarkers = new Set(["top-level", ...importableDefinitionNames]);
const foundMarkers = new Set();
const source = readFileSync(outputPath, "utf8");

const generated = source.replace(markerPattern, (_block, name) => {
    if (!expectedMarkers.has(name)) {
        throw new Error(`Unknown importables schema marker: ${name}`);
    }
    if (foundMarkers.has(name)) {
        throw new Error(`Duplicate importables schema marker: ${name}`);
    }
    foundMarkers.add(name);
    const schema =
        name === "top-level" ? IMPORT_JSON_SCHEMA : IMPORT_JSON_SCHEMA_DEFINITIONS[name];
    if (schema?.kind !== "object") {
        throw new Error(`Schema marker ${name} does not refer to an object`);
    }
    return [
        `<!-- importables-schema:${name} START -->`,
        "<!-- Generated by scripts/gen-importables-doc.mjs. Do not edit this block. -->",
        "",
        renderObjectTable(schema, { expandNested: name !== "top-level" }),
        `<!-- importables-schema:${name} END -->`,
    ].join("\n");
});

const missingMarkers = [...expectedMarkers].filter((name) => !foundMarkers.has(name));
if (missingMarkers.length > 0) {
    throw new Error(
        `docs/importables.md is missing schema markers: ${missingMarkers.join(", ")}`
    );
}

if (checkOnly) {
    if (generated !== source) {
        throw new Error(
            "docs/importables.md is stale; run npm --prefix scripts run generate:docs:importables"
        );
    }
} else {
    writeFileSync(outputPath, generated, "utf8");
}

function renderObjectTable(schema, options) {
    const rows = [];
    const details = [];
    collectRows(schema, "", rows, details, options);
    const lines = [
        "| Field | Required | Value |",
        "| --- | --- | --- |",
        ...rows.map(
            ({ field, required, value }) =>
                `| \`${escapeTable(field)}\` | ${required ? "Yes" : "No"} | ${escapeTable(value)} |`
        ),
    ];
    if (rows.some(({ field }) => field.includes(".") || field.includes("[]"))) {
        lines.unshift(
            "Nested fields marked required are required whenever their containing object is present.",
            ""
        );
    }

    for (const detail of details) {
        lines.push(
            "",
            "<details>",
            `<summary>Accepted ${detail.kind} for <code>${escapeHtml(detail.field)}</code> (${detail.values.length})</summary>`,
            "",
            detail.values.map((value) => `\`${value}\``).join(", "),
            "",
            "</details>"
        );
    }
    lines.push("");
    return lines.join("\n");
}

function collectRows(schema, prefix, rows, details, options) {
    for (const [key, property] of Object.entries(schema.properties)) {
        const field = prefix.length === 0 ? key : `${prefix}.${key}`;
        rows.push({
            field,
            required: property.required,
            value: describeSchema(property, field, details),
        });
        if (!options.expandNested) continue;

        const object = referencedObject(property);
        if (object !== undefined) {
            if (Object.keys(object.properties).length > 12) {
                details.push({
                    field,
                    kind: "fields",
                    values: Object.keys(object.properties),
                });
            } else {
                collectRows(object, field, rows, details, options);
            }
            continue;
        }

        if (property.kind === "array") {
            const itemObject = referencedObject(property.items);
            if (itemObject !== undefined) {
                collectRows(itemObject, `${field}[]`, rows, details, options);
            }
        }
    }
}

function describeSchema(schema, field, details) {
    if (schema.kind === "ref") {
        const target = IMPORT_JSON_SCHEMA_DEFINITIONS[schema.ref];
        if (target === undefined) return humanize(schema.ref);
        if (target.kind === "object") return `${humanize(schema.ref)} object`;
        return describeSchema(target, field, details);
    }
    if (schema.kind === "string") {
        if (schema.enum !== undefined) {
            if (schema.enum.length <= 6) {
                return `one of ${schema.enum.map((value) => `\`${value}\``).join(", ")}`;
            }
            details.push({ field, kind: "values", values: schema.enum });
            return `one of ${schema.enum.length} accepted strings`;
        }
        if (schema.pattern !== undefined) {
            if (schema.pattern.includes("[0-9a-fA-F]{8}")) return "UUID string";
            if (schema.pattern === "\\.htsl$") return "path ending in `.htsl`";
            if (schema.pattern === "\\.snbt$") return "path ending in `.snbt`";
            if (schema.pattern.includes("[iI][mM][pP][oO][rR][tT]")) {
                return "path ending in `import.json` or `.import.json`";
            }
            return `string matching \`${schema.pattern}\``;
        }
        return "string";
    }
    if (schema.kind === "number") {
        const type = schema.integer === true ? "integer" : "number";
        if (schema.minimum !== undefined && schema.maximum !== undefined) {
            return `${type} from ${schema.minimum} to ${schema.maximum}`;
        }
        if (schema.minimum !== undefined) return `${type} at least ${schema.minimum}`;
        if (schema.maximum !== undefined) return `${type} at most ${schema.maximum}`;
        return type;
    }
    if (schema.kind === "boolean") return "boolean";
    if (schema.kind === "array") {
        return `array of ${describeSchema(schema.items, `${field}[]`, details)}`;
    }
    return "object";
}

function referencedObject(schema) {
    if (schema.kind !== "ref") return undefined;
    const target = IMPORT_JSON_SCHEMA_DEFINITIONS[schema.ref];
    return target?.kind === "object" ? target : undefined;
}

function humanize(value) {
    const words = value
        .replace(/Importable$/, "")
        .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
        .toLowerCase();
    if (words === "pos") return "position";
    return words.replace(/^npc\b/, "NPC");
}

function escapeTable(value) {
    return String(value).replaceAll("|", "\\|").replaceAll("\n", " ");
}

function escapeHtml(value) {
    return String(value)
        .replaceAll("&", "&amp;")
        .replaceAll("<", "&lt;")
        .replaceAll(">", "&gt;");
}
