import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { build } from "esbuild";

const repositoryRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);

const bundledLanguage = await build({
  absWorkingDir: repositoryRoot,
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node22",
  write: false,
  stdin: {
    contents: `
            export {
                resolveVanillaItemReference,
                vanillaVariationReferenceName,
                VANILLA_VARIATION_REFERENCE_COLLISIONS,
            } from "./language/dist/items/index.js";
            export { MINECRAFT_ITEMS } from "./language/dist/types/constants.js";
        `,
    resolveDir: repositoryRoot,
  },
});
const language = await import(
  `data:text/javascript;base64,${Buffer.from(bundledLanguage.outputFiles[0].text).toString("base64")}`
);

const rows = [];
const documentedNames = new Set();

function addResolvedName(name, displayName) {
  if (documentedNames.has(name)) return;

  const resolved = language.resolveVanillaItemReference(name);
  if (resolved === undefined) return;

  const damage = resolved.nbt.value.Damage?.value;
  if (typeof damage !== "number") {
    throw new Error(`Resolver returned no numeric Damage tag for ${name}`);
  }

  documentedNames.add(name);
  rows.push({ name, id: resolved.id, damage, displayName });
}

for (const item of language.MINECRAFT_ITEMS) {
  addResolvedName(`minecraft:${item.name}`, item.displayName);
  for (const variation of item.variations ?? []) {
    const name = language.vanillaVariationReferenceName(variation.displayName);
    addResolvedName(name, variation.displayName);
  }
}

const lines = [
  "<!-- Generated by scripts/gen-items-doc.mjs. Do not edit by hand. -->",
  "",
  "# Vanilla Item Names",
  "",
  "[HTSL item fields](./htsl/actions.md) accept the name of an ITEM importable, one of the vanilla names below, or a direct `.snbt` path. Base IDs require the `minecraft:` prefix; a bare name such as `stone` does not resolve. Derived variant names work either bare or with the `minecraft:` prefix. Different names that resolve to the same ID and damage value are the same item to the importer.",
  "",
  "<details>",
  `<summary>Full list (${rows.length} names)</summary>`,
  "",
  "| Name | Resolves to | In-game display name |",
  "| --- | --- | --- |",
  ...rows.map(
    ({ name, id, damage, displayName }) =>
      `| \`${name}\` | \`${id}\`, damage ${damage} | ${displayName.replaceAll("|", "\\|")} |`,
  ),
  "",
  "</details>",
  "",
];

if (language.VANILLA_VARIATION_REFERENCE_COLLISIONS.length > 0) {
  const ambiguousNames = language.VANILLA_VARIATION_REFERENCE_COLLISIONS.map(
    (name) => `\`${name}\``,
  ).join(", ");
  lines.push(
    "## Ambiguous names",
    "",
    `The derived names ${ambiguousNames} are ambiguous and refuse to resolve.`,
    "",
  );
}

await writeFile(
  path.join(repositoryRoot, "docs", "vanilla-item-names.md"),
  lines.join("\n"),
  "utf8",
);
